#!/usr/bin/env python3
"""
Regenerate S7 gold answers for the frozen question set.

Why this exists
---------------
The first S7 freeze (s7_v1, sha256 d7114022...) was generated by a script
that serialised the executor selectors as explicit nulls:

    {"op": "count", "target": "dosha", ..., "a": null, "b": null}

`Query` defaults those selectors to "previous"/"last", so passing null
overrode the defaults and every such plan failed validation with
`bad selector None`. The generator recorded that construction error as the
gold answer ("status": "error", "value": "bad selector None"), and the
runner rebuilt the same malformed query, got the same error, and scored
error-vs-error as a pass. 650 of the 810 questions therefore measured
nothing: the reported 810/810 was a tautology.

The questions themselves (id, text, frame, patient, plan) are sound -- only
the selector serialisation was wrong. This script recomputes the gold
answers from the *unchanged* frozen plans using corrected plan->Query
construction, so the holdout stays unseen while its gold becomes real.

    ./venv/bin/python scripts/regenerate_s7_gold.py --db db/ayurcore.db

Writes the corrected questions file and manifest, and appends a correction
record to the manifest so the defect and its fix stay visible.

SYNTHETIC; NOT CLINICAL DATA.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sqlite3
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from ai2.snapshot import snapshot_from_records
from backend.encounter_store import list_encounters_for_patient
from backend.patient_store import get_patient_for_clinic, get_prescription_history, read_snapshot
from memory.executor import execute
from scripts.s7_generator import query_from_plan

S7_DATA_DIR = ROOT / "eval" / "benchmarks" / "s7"
S7_REPORT_DIR = ROOT / "eval" / "reports" / "s7"
DATA_FILE = S7_DATA_DIR / "s7_unseen.json"
DATA_MANIFEST = S7_DATA_DIR / "manifest.json"
MANIFEST_FILE = S7_REPORT_DIR / "manifest.json"  # canonical record (final/frozen/evaluation/corrections)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build_snapshot(db_path: str, clinic_id: str, patient_pk: int):
    """Read-only snapshot for one patient, from the demo database."""
    import db.database as db_database

    original = db_database.DB_PATH
    db_database.DB_PATH = db_path
    try:
        with read_snapshot() as conn:
            patient = get_patient_for_clinic(patient_pk, clinic_id, conn=conn)
            if patient is None:
                raise LookupError(f"patient {patient_pk} not in {clinic_id}")
            rx_records, offset = [], 0
            while True:
                page, more = get_prescription_history(
                    clinic_id, patient["patient_pk"], 50, offset, conn=conn
                )
                rx_records += page
                offset += 50
                if not more:
                    break
            enc_records, offset = [], 0
            while True:
                page, more = list_encounters_for_patient(
                    clinic_id, patient["patient_pk"], 50, offset, conn=conn
                )
                enc_records += page
                offset += 50
                if not more:
                    break
    finally:
        db_database.DB_PATH = original
    return snapshot_from_records(clinic_id, patient["patient_pk"], rx_records, enc_records)


def main() -> int:
    parser = argparse.ArgumentParser(description="Recompute S7 gold answers")
    parser.add_argument("--db", default=str(ROOT / "db" / "ayurcore.db"))
    parser.add_argument("--dry-run", action="store_true", help="report, write nothing")
    args = parser.parse_args()

    data = json.loads(DATA_FILE.read_text())
    manifest = json.loads(MANIFEST_FILE.read_text())
    before_hash = sha256(DATA_FILE)

    conn = sqlite3.connect(args.db)
    conn.row_factory = sqlite3.Row
    before = Counter(q["gold_answer"].get("status") for q in data["questions"])

    cache: dict[tuple[str, str], object] = {}
    changed = 0
    after = Counter()

    for question in data["questions"]:
        clinic_id, clinic_patient_id = question["patient"].split("/")
        plan = question["gold_plan"]

        if plan["kind"] == "abstain":
            gold = {"status": "refused", "value": None, "sources": []}
        else:
            row = conn.execute(
                "SELECT patient_pk FROM patients WHERE clinic_id = ? AND clinic_patient_id = ?",
                (clinic_id, clinic_patient_id),
            ).fetchone()
            if row is None:
                raise SystemExit(f"patient missing from {args.db}: {question['patient']}")
            key = (clinic_id, row["patient_pk"])
            if key not in cache:
                cache[key] = build_snapshot(args.db, clinic_id, row["patient_pk"])
            query = query_from_plan(plan["query"])
            try:
                result = execute(cache[key], query)
            except Exception as exc:  # a malformed plan must never become gold
                raise SystemExit(f"{question['id']}: plan failed to execute: {query} -> {exc!r}")
            gold = {
                "status": result.status,
                "value": result.value,
                "sources": [e.label for e in result.evidence] + list(result.unknown_sources),
            }

        if gold != question["gold_answer"]:
            changed += 1
            question["gold_answer"] = gold
        after[gold["status"]] += 1

    conn.close()

    print(f"gold status before: {dict(before)}")
    print(f"gold status after : {dict(after)}")
    print(f"answers rewritten : {changed}/{len(data['questions'])}")

    if args.dry_run:
        print("dry run: nothing written")
        return 0

    DATA_FILE.write_text(json.dumps(data, indent=2) + "\n")
    new_hash = sha256(DATA_FILE)

    manifest.setdefault("corrections", []).append({
        "version": 2,
        "date": "2026-10-29",
        "defect": "Selectors were serialised as explicit nulls in gold plans; "
                  "Query validation rejected them ('bad selector None') and the "
                  "generator recorded the construction error as the gold answer. "
                  "The runner rebuilt the same malformed query, so error-vs-error "
                  "scored as a pass.",
        "impact": "650 of 810 questions carried a construction error instead of a "
                  "gold answer; the previously reported 810/810 pass rate was invalid.",
        "fix": "Recomputed gold answers from the unchanged frozen plans with "
               "plan->Query construction that omits unset selectors. Questions, "
               "frames, patients and plans are untouched, so the holdout remains unseen.",
        "gold_status_before": dict(before),
        "gold_status_after": dict(after),
        "answers_rewritten": changed,
        "sha256_before": before_hash,
        "sha256_after": new_hash,
    })
    # A superseded evaluation result must not sit next to a corrected dataset.
    manifest["evaluation"] = {
        "status": "pending",
        "note": "Superseded by the v2 gold correction. Re-run scripts/run_s7_evaluation.py.",
    }
    manifest.setdefault("file_sha256", {})["s7_unseen.json"] = new_hash
    MANIFEST_FILE.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST_FILE.write_text(json.dumps(manifest, indent=2) + "\n")

    # The data-local manifest only carries integrity data; the report manifest
    # is the canonical record of what this dataset is and how it scored.
    data_manifest = json.loads(DATA_MANIFEST.read_text())
    data_manifest["file_sha256"]["s7_unseen.json"] = new_hash
    data_manifest["canonical_manifest"] = "eval/reports/s7/manifest.json"
    data_manifest.pop("corrections", None)
    data_manifest.pop("evaluation", None)
    DATA_MANIFEST.write_text(json.dumps(data_manifest, indent=2) + "\n")
    print(f"wrote {DATA_FILE}")
    print(f"wrote {DATA_MANIFEST}")
    print(f"wrote {MANIFEST_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
