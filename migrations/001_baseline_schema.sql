-- Migration 001: baseline schema.
--
-- This represents the schema exactly as it existed BEFORE a real migration
-- system existed in this project -- every statement here is copied from
-- db/database.py's old init_db(), unchanged. It is deliberately written as
-- CREATE TABLE IF NOT EXISTS / CREATE INDEX IF NOT EXISTS everywhere, which
-- makes it safe to run against two very different starting points with the
-- exact same file:
--
--   1. A brand new, empty database -- every statement below actually
--      creates something. This is the bootstrap path.
--   2. This project's real, already-running ayurcore.db, whose tables were
--      created by the old init_db() before this migration system existed --
--      every statement below is a no-op against it (the tables and indexes
--      already exist), so applying this migration does not touch, alter,
--      or lose a single existing row. This is the upgrade path.
--
-- Do NOT edit this file once it has been applied anywhere -- the migration
-- runner checksums every applied migration and refuses to proceed if an
-- already-applied file's content changes underneath it. A schema change
-- from here on is always a NEW, higher-numbered migration file, never an
-- edit to this one.

CREATE TABLE IF NOT EXISTS inventory (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    clinic_id TEXT NOT NULL DEFAULT 'default_clinic',
    herb_name TEXT NOT NULL,
    botanical_name TEXT NOT NULL,
    stock_grams INTEGER NOT NULL CHECK (stock_grams >= 0),
    batch_code TEXT NOT NULL,
    potency_score INTEGER NOT NULL CHECK (potency_score >= 0 AND potency_score <= 100)
);

CREATE INDEX IF NOT EXISTS idx_inventory_herb_name ON inventory(herb_name);
CREATE INDEX IF NOT EXISTS idx_inventory_clinic_herb ON inventory(clinic_id, herb_name);

CREATE TABLE IF NOT EXISTS prescriptions (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    clinic_id TEXT NOT NULL DEFAULT 'default_clinic',
    patient_name TEXT NOT NULL,
    description TEXT NOT NULL,
    status TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_prescriptions_patient_name ON prescriptions(patient_name);
CREATE INDEX IF NOT EXISTS idx_prescriptions_created_at ON prescriptions(created_at);
CREATE INDEX IF NOT EXISTS idx_prescriptions_clinic_id ON prescriptions(clinic_id);

-- NOTE: deliberately NO clinic_id here -- this table is being represented
-- exactly as it exists in the live database today. See migration 002 for
-- the decision to add clinic_id to this table and why.
CREATE TABLE IF NOT EXISTS panchakarma_resources (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    name TEXT NOT NULL,
    quantity INTEGER NOT NULL,
    resource_type TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS corrections (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    prescription_id INTEGER NOT NULL REFERENCES prescriptions(id),
    clinic_id TEXT NOT NULL DEFAULT 'default_clinic',
    ai_dosha_imbalance TEXT NOT NULL,
    ai_prescribed_herbs_json TEXT NOT NULL,
    confirmed_dosha_imbalance TEXT NOT NULL,
    confirmed_prescribed_herbs_json TEXT NOT NULL,
    was_changed INTEGER NOT NULL CHECK (was_changed IN (0, 1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_corrections_clinic_id ON corrections(clinic_id);
CREATE INDEX IF NOT EXISTS idx_corrections_was_changed ON corrections(was_changed);
CREATE INDEX IF NOT EXISTS idx_corrections_prescription_id ON corrections(prescription_id);
